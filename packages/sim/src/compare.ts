import type { Prediction, RuleSet } from "@bull-city-blocks/engine";
import type { Metrics } from "./metrics";
import type { Estimate } from "./stats";

/** Base vs variant on paired seeds (SPEC §5–6). A metric is "changed" when the 95% CIs don't overlap. */

export const overlaps = (a: Estimate, b: Estimate) => a.low <= b.high && b.low <= a.high;

/** The scalar metrics a prediction can name. */
export const SCALARS: Record<Prediction["metric"], (m: Metrics) => Estimate> = {
  stallRate: (m) => m.stallRate,
  comebackRate: (m) => m.comebackRate,
  turnsToWin: (m) => m.turnsToWin.mean,
  roundsToWin: (m) => m.roundsToWin.mean,
  reshuffles: (m) => m.reshuffles,
};

export interface Row {
  metric: string;
  base: Estimate;
  variant: Estimate;
  changed: boolean;
}

export function compareMetrics(base: Metrics, variant: Metrics): Row[] {
  const row = (metric: string, b: Estimate, v: Estimate): Row => ({
    metric,
    base: b,
    variant: v,
    changed: !overlaps(b, v),
  });
  return [
    ...base.winRateBySeat.map((b, i) =>
      row(`win rate, seat ${i + 1}`, b, variant.winRateBySeat[i] as Estimate),
    ),
    ...Object.entries(SCALARS).map(([name, get]) => row(name, get(base), get(variant))),
    ...Object.keys(base.botWinRate).map((bot) =>
      row(
        `win rate, ${bot} bot`,
        base.botWinRate[bot] as Estimate,
        variant.botWinRate[bot] as Estimate,
      ),
    ),
  ];
}

export type Verdict = "supported" | "not supported" | "inconclusive";
export interface PlayerCount {
  players: number;
  base: Metrics;
  variant: Metrics;
}

/**
 * Judges one prediction at each player count it covers: "holds" when the CIs show the predicted
 * change (or, for "same", overlap), "contradicted" when they show the opposite, otherwise "unclear".
 * Any contradiction → not supported; all hold → supported; otherwise inconclusive.
 */
export function judge(prediction: Prediction, counts: readonly PlayerCount[]) {
  const [from, to] = prediction.players;
  const outcomes = counts
    .filter((c) => c.players >= from && c.players <= to)
    .map((c) => {
      const b = SCALARS[prediction.metric](c.base);
      const v = SCALARS[prediction.metric](c.variant);
      const changed = !overlaps(b, v);
      const direction = v.value < b.value ? "lower" : "higher";
      const outcome =
        prediction.expect === "same"
          ? changed
            ? "contradicted"
            : "holds"
          : !changed
            ? "unclear"
            : direction === prediction.expect
              ? "holds"
              : "contradicted";
      return { players: c.players, outcome };
    });
  const verdict: Verdict =
    outcomes.length === 0
      ? "inconclusive"
      : outcomes.some((o) => o.outcome === "contradicted")
        ? "not supported"
        : outcomes.every((o) => o.outcome === "holds")
          ? "supported"
          : "inconclusive";
  return { prediction, outcomes, verdict };
}

export function overallVerdict(verdicts: readonly Verdict[]): Verdict {
  if (verdicts.length === 0) return "inconclusive";
  if (verdicts.includes("not supported")) return "not supported";
  return verdicts.every((v) => v === "supported") ? "supported" : "inconclusive";
}

const fmt = (e: Estimate, rate: boolean) =>
  rate
    ? `${(100 * e.value).toFixed(1)}% [${(100 * e.low).toFixed(1)}–${(100 * e.high).toFixed(1)}]`
    : `${e.value.toFixed(2)} [${e.low.toFixed(2)}–${e.high.toFixed(2)}]`;

/** The Markdown report for reports/<variant>.md. Every verdict and flag is computed above. */
export function formatReport(
  variant: RuleSet,
  base: string,
  games: number,
  bots: readonly string[],
  counts: readonly PlayerCount[],
): string {
  const judged = (variant.predictions ?? []).map((p) => judge(p, counts));
  const lines = [
    `# Variant report: \`${variant.id}\``,
    "",
    `> ${variant.description}`,
    "",
    `Generated by \`pnpm sim --base ${base} --variant ${variant.id} --games ${games}\`, with bots ${bots.map((b) => `\`${b}\``).join(", ")} rotating seats.`,
    `Both rulesets play the **same seeds** (\`sim:<players>:<game>\`), ${games.toLocaleString("en-US")} games per player count. A metric is **changed** when the 95% confidence intervals don't overlap (Wilson intervals for rates).`,
    "",
    "## Hypothesis",
    "",
    `> ${variant.hypothesis ?? "(none given)"}`,
    "",
    `**Verdict: ${overallVerdict(judged.map((j) => j.verdict))}**, computed from the predictions below.`,
    "",
    "| Prediction | Per player count | Verdict |",
    "|---|---|---|",
    ...judged.map(
      (j) =>
        `| \`${j.prediction.metric}\` ${j.prediction.expect} at ${j.prediction.players[0]}–${j.prediction.players[1]} players | ${j.outcomes.map((o) => `${o.players}p: ${o.outcome}`).join(", ")} | ${j.verdict} |`,
    ),
  ];
  for (const c of counts) {
    lines.push(
      "",
      `## ${c.players} players`,
      "",
      `| Metric | ${base} | ${variant.id} | Changed |`,
      "|---|---|---|---|",
    );
    for (const r of compareMetrics(c.base, c.variant)) {
      const rate = /rate/i.test(r.metric);
      lines.push(
        `| ${r.metric} | ${fmt(r.base, rate)} | ${fmt(r.variant, rate)} | ${r.changed ? "**changed**" : ""} |`,
      );
    }
  }
  return `${lines.join("\n")}\n`;
}
